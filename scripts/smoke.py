"""Step 3: start the server in a minimal configuration, send one chat request, write results/smoke.md."""

import json
import os

from llsrv import MODEL, WORK, Server, http

ARGS = ["-m", MODEL, "-c", "8192", "--jinja", "-ngl", "99", "-cmoe"]
PROMPT = "What is a mixture-of-experts language model? Answer in three sentences."


def main():
    srv = Server(ARGS, os.path.join(WORK, "runs", "smoke", "server.log"))
    with srv:
        props = http(srv.port, "/props")
        r = http(srv.port, "/v1/chat/completions", {"messages": [{"role": "user", "content": PROMPT}], "max_tokens": 1024, "seed": 1234})
    json.dump(props, open(os.path.join(WORK, "runs", "smoke", "props.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(r, open(os.path.join(WORK, "runs", "smoke", "response.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    gen = props.get("default_generation_settings", {})
    params = gen.get("params", gen)
    keys = ["temperature", "top_k", "top_p", "min_p", "repeat_penalty", "presence_penalty", "frequency_penalty", "samplers", "reasoning_effort", "reasoning_format", "n_predict", "seed"]
    used = {k: params[k] for k in keys if k in params}
    msg = r["choices"][0]["message"]
    t = r["timings"]
    lines = [
        "# Step 3 smoke test",
        "",
        "Generated by `scripts/smoke.py`. Raw files: `runs/smoke/`.",
        "",
        "## Server arguments",
        "",
        "```",
        "llama-server " + " ".join(a if a != MODEL else "models/" + os.path.basename(MODEL) for a in ARGS),
        "```",
        "",
        "## Sampling and reasoning values in effect (server defaults, from /props)",
        "",
        "```json",
        json.dumps(used, ensure_ascii=False, indent=1),
        "```",
        "",
        f"The request set only `max_tokens` (1024) and `seed` (1234). `reasoning_effort` was not sent, so the template default applies.",
        "",
        "## Request",
        "",
        "> " + PROMPT,
        "",
        "## Response",
        "",
        f"- finish_reason: `{r['choices'][0]['finish_reason']}`",
        f"- usage: `{json.dumps(r.get('usage', {}))}`",
        f"- reasoning_content: {len(msg.get('reasoning_content') or '')} chars",
        f"- prompt eval: {t['prompt_n']} tokens, {t['prompt_per_second']:.1f} t/s",
        f"- eval: {t['predicted_n']} tokens, {t['predicted_per_second']:.2f} t/s",
        f"- server exit code: {srv.proc.returncode}",
        "",
        "```",
        (msg.get("content") or "").strip(),
        "```",
        "",
    ]
    open(os.path.join(WORK, "results", "smoke.md"), "w", encoding="utf-8").write("\n".join(lines))
    print("\n".join(lines))
    print("chat template caps:", json.dumps(props.get("chat_template_caps", {})))


if __name__ == "__main__":
    main()
